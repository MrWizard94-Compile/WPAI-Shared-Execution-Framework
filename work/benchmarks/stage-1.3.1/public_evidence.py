"""Verify archival SHA-256 digests and reproduce the Stage 1.3.1 comparison proof."""

import argparse
import json
from pathlib import Path

from comparator import report
from evidence import ROOT, ROUTES, TOOLS, digest, read


HERE = Path(__file__).resolve().parent
OUTPUT = ROOT / "outputs" / "stage-1.3.1"
BASELINE = "ec7ea9d5c88a6d8adee65fd2fd5518947f39a687"


def verify_history():
    history = read(OUTPUT / "historical-sha256.json")
    if history["baseline_commit"] != BASELINE:
        raise ValueError("Unexpected historical baseline")
    for path, expected in history["files"].items():
        data = (ROOT / path).read_bytes()
        if len(data) != expected["bytes"] or digest(data) != expected["sha256"]:
            raise ValueError(f"Historical bytes differ for {path}")
    for path, expected in history["append_only_documentation"].items():
        original_bytes = expected["bytes"]
        if digest((ROOT / path).read_bytes()[:original_bytes]) != expected["sha256"]:
            raise ValueError(f"Original documentation bytes differ for {path}")
    return history


def verification():
    history = verify_history()
    current = report()
    legacy = read(ROOT / "outputs" / "stage-1.3" / "reconciliation.json")
    if current["source_record_sha256"] != legacy["source_record_sha256"]:
        raise ValueError("Raw run inventory differs")
    if current["frozen_identities"] != legacy["frozen_identities"]:
        raise ValueError("Fixture identities differ")
    schedule_path = "outputs/stage-1.3/repeatability-plan.json"
    plan = read(ROOT / schedule_path)
    if plan["live_inference_authorized"] is not False or plan["session_counts"]["authorized_now"] != 0:
        raise ValueError("Archived plan authorized inference")
    dispositions = {}
    for provider in ROUTES:
        old, corrected = legacy["providers"][provider], current["providers"][provider]
        keys = ("pair_eligible", "resource_metrics_eligible", "historical_observed_reduction_fractions")
        if any(old[key] != corrected[key] for key in keys):
            raise ValueError(f"Historical disposition or reduction differs for {provider}")
        for arm in TOOLS:
            checks = ("answer_valid", "tool_execution_valid", "lifecycle_status", "client_observed_result_bytes_available")
            if any(old[arm][key] != corrected[arm][key] for key in checks):
                raise ValueError(f"Historical run outcomes differ for {provider} {arm}")
        dispositions[provider] = {**{key: corrected[key] for key in keys}, "arms": {
            arm: {key: corrected[arm][key] for key in checks} for arm in TOOLS}}
    if set(legacy["discarded_attempts"]) != set(current["discarded_attempts"]):
        raise ValueError("Discarded attempt inventory differs")
    sources = {path.relative_to(ROOT).as_posix(): digest(path.read_bytes()) for path in sorted(HERE.rglob("*.py"))}
    return {
        "schema": "wpai.benchmark.correction-verification.v1",
        "accepted_baseline": BASELINE,
        "constitution": "0adf5ecee5f7f96ce3749944dc097a003731a6e9",
        "historical_manifest_sha256": digest((OUTPUT / "historical-sha256.json").read_bytes()),
        "historical_files_verified": len(history["files"]),
        "original_documentation_prefixes_verified": len(history["append_only_documentation"]),
        "source_and_test_sha256": sources,
        "historical_routes": dispositions,
        "discarded_attempts_preserved": len(current["discarded_attempts"]),
        "unchanged_schedule_sha256": history["files"][schedule_path]["sha256"],
        "planned_pairs_per_route": {route: plan["routes"][route]["paired_runs"] for route in ROUTES},
        "unchanged_planned_session_counts": plan["session_counts"],
    }


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--write", action="store_true", help="Regenerate only the versioned Stage 1.3.1 proof")
    args = parser.parse_args()
    path = OUTPUT / "verification.json"
    expected = (json.dumps(verification(), indent=2, allow_nan=False) + "\n").encode()
    if args.write:
        path.write_bytes(expected)
    elif path.read_bytes() != expected:
        raise SystemExit("Stage 1.3.1 verification differs from regenerated bytes")
    print("Verified historical SHA-256 digests and deterministic Stage 1.3.1 evidence.")


if __name__ == "__main__":
    main()
